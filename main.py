import os
from openai import OpenAI

client = OpenAI(api_key=os.environ["OPENAI_API_KEY"])

with open("brain.md", "r", encoding="utf-8") as file:
    brain = file.read()

task = """
Ти си KINEZI AI — интелигентен асистент за съдържанието на KINEZI CORE.

Създай една интересна, образователна и полезна публикация за Facebook.

Сам избери тема, като редуваш различни направления:

- Какво е ядрото и как работи
- Гръбначен стълб и стави
- Упражнения и правилното им изпълнение
- Сила, стабилност, баланс и координация
- Движение и ежедневни навици
- Стойка и двигателни навици
- Нервна система, стрес и възстановяване
- Сън и начин на живот
- Болка и съвременни разбирания за нея
- Интересни научни факти
- Нови научни открития
- Митове и заблуди за движението
- Практични съвети за по-здраво и функционално тяло

Ако избираш тема за упражнение:
- обясни как се изпълнява;
- обясни какво развива;
- посочи най-честите грешки;
- дай разумни насоки за безопасно изпълнение.

Не насърчавай упражнения през болка.
Не препоръчвай крайни амплитуди или агресивно разтягане.
Не представяй едно упражнение като универсално решение за всички.
Не използвай плашещ или драматичен език.

Пиши на естествен и разбираем български.
Публикацията трябва да е интересна и за човек, който не разбира от анатомия или физиология.

Веднъж седмично съдържанието трябва естествено да насърчава хората да посетят KINEZI CORE.
Тази покана трябва да бъде полезна и ненатрапчива, а не агресивна реклама.

Когато е подходящо, завършвай с въпрос към читателя, който насърчава разговор и коментари.

Не измисляй научни факти, изследвания или източници.
Ако дадена информация не е сигурна, кажи ясно, че доказателствата са ограничени или че темата все още се изследва.

ВАЖНО:
Това е първи тест. Засега не търси интернет и не създавай изображение.
Само създай текста на публикацията.
"""

response = client.responses.create(
    model="gpt-5-mini",
    instructions=brain,
    input=task
)

print("KINEZI AI създаде:")
print(response.output_text)
